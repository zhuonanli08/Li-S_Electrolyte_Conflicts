def meta():
    yr = {}
    for d in PAPERS.iterdir():
        f = d / "input_meta.json"
        yr[d.name] = (json.loads(f.read_text(encoding="utf-8")).get("year") or None) if f.exists() else None
    flags = defaultdict(lambda: {"贫液": False, "高载量": False, "三项": False})
    for t in json.loads(COND.read_text(encoding="utf-8")):
        if t.get("测试类型") != "全电池性能":
            continue
        c = t["条件"]
        v = lambda k: (c.get(k) or {}).get("值") if isinstance(c.get(k), dict) else None
        es, ld, li, np_ = v("ES"), v("sulfur_loading"), v("Li_thickness"), v("NP")
        lean, high = es is not None and es <= 5, ld is not None and ld >= 4
        thin = (li is not None and li <= 50) or (isinstance(np_, (int, float)) and np_ <= 3)
        f = flags[t["论文"]]
        f["贫液"] |= lean
        f["高载量"] |= high
        f["三项"] |= lean and high and thin
    return yr, flags


